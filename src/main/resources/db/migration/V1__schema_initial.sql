-- Schéma initial : utilisateurs, applications, demandes d'habilitation et leur historique.

create table utilisateur (
    id           bigint generated by default as identity primary key,
    email        varchar(255) not null unique,
    mot_de_passe varchar(255) not null,
    nom_complet  varchar(255) not null,
    role         varchar(20)  not null
);

create table application (
    id          bigint generated by default as identity primary key,
    code        varchar(50)   not null unique,
    nom         varchar(255)  not null,
    description varchar(1000)
);

create table demande_habilitation (
    id             bigint generated by default as identity primary key,
    demandeur_id   bigint        not null references utilisateur (id),
    application_id bigint        not null references application (id),
    profil         varchar(50)   not null,
    justification  varchar(1000) not null,
    statut         varchar(20)   not null,
    date_creation  timestamp with time zone not null,
    date_maj       timestamp with time zone not null
);

create index idx_demande_demandeur on demande_habilitation (demandeur_id);
create index idx_demande_statut on demande_habilitation (statut);

create table historique_statut (
    id             bigint generated by default as identity primary key,
    demande_id     bigint       not null references demande_habilitation (id),
    ancien_statut  varchar(20),
    nouveau_statut varchar(20)  not null,
    auteur_id      bigint       not null references utilisateur (id),
    commentaire    varchar(500),
    date_action    timestamp with time zone not null
);

create index idx_historique_demande on historique_statut (demande_id);
